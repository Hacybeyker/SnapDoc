package com.hacybeyker.snapdoc.feature.library.data

import com.hacybeyker.snapdoc.core.document.DocumentInsight
import com.hacybeyker.snapdoc.core.document.DocumentKind
import com.hacybeyker.snapdoc.core.document.InsightSource
import com.hacybeyker.snapdoc.feature.library.domain.StoredDocument

internal fun DocumentEntity.toStoredDocument() = StoredDocument(
    id = id,
    imagePaths = imagePaths.split(PATH_SEPARATOR),
    createdAtEpochMillis = createdAtEpochMillis,
    text = text,
    insight = DocumentInsight(
        kind = kind.toDocumentKind(),
        merchant = merchant,
        date = date,
        total = total,
        source = insightSource.toInsightSource()
    )
)

/** The row keeps `id = 0`: it is autogenerated, and a saved scan is identified by its pages. */
internal fun StoredDocument.toEntity() = DocumentEntity(
    imagePaths = imagePaths.joinToString(PATH_SEPARATOR),
    createdAtEpochMillis = createdAtEpochMillis,
    pageCount = imagePaths.size,
    text = text,
    kind = insight.kind.name,
    merchant = insight.merchant,
    date = insight.date,
    total = insight.total,
    insightSource = insight.source.name
)

/**
 * Enums are stored by name and read back defensively. A row written by a newer build can name a kind
 * this one has never heard of, and falling back beats crashing on someone's own archive.
 */
private fun String.toDocumentKind(): DocumentKind =
    DocumentKind.entries.firstOrNull { it.name == this } ?: DocumentKind.Unknown

private fun String.toInsightSource(): InsightSource =
    InsightSource.entries.firstOrNull { it.name == this } ?: InsightSource.Rules
